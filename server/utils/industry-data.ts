// 板块名称列表（便于遍历）
export const INDUSTRY_NAMES = Object.keys(INDUSTRY_DATA)

/**
 * 获取指定板块的行业详情
 */
export function getIndustryInfo(name: string): IndustryInfo | undefined {
  return INDUSTRY_DATA[name]
}

/**
 * 模糊匹配板块名称
 */
export function findIndustry(keyword: string): IndustryInfo | undefined {
  if (INDUSTRY_DATA[keyword]) return INDUSTRY_DATA[keyword]
  const found = INDUSTRY_NAMES.find(name =>
    name.includes(keyword) || keyword.includes(name)
  )
  return found ? INDUSTRY_DATA[found] : undefined
}
